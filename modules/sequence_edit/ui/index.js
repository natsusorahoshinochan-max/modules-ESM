  function Viewer({ package: pkg, host }) {
    const [data, setData] = React.useState(null),
      [error, setError] = React.useState("");
    React.useEffect(() => {
      let live = true;
      host
        .readFile(pkg.id, pkg.entry)
        .then((blob) => blob.text())
        .then((text) => {
          if (live) setData(JSON.parse(text));
        })
        .catch((reason) => {
          if (live) setError(i18n.error(reason));
        });
      return () => {
        live = false;
      };
    }, [pkg.id]);
    return error
      ? h("p", { role: "alert" }, error)
      : data
        ? h(
            "section",
            null,
            h("p", null, t("positions", {"0": data.tracks.sequence.length})),
            h("pre", null, data.tracks.sequence.map((v) => v ?? "·").join("")),
          )
        : h("p", null, t("reading"));
  }
