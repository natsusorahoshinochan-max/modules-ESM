import { expect, test } from '@playwright/test'
const appUrl = process.env.WORKBENCH_TEST_URL ?? 'http://127.0.0.1:5393'
const wheel = process.env.WORKBENCH_MODULE_WHEEL!

test('empty carrier installs an external wheel, edits and runs it, preserves missing nodes and restores them', async ({ page, request }) => {
  test.setTimeout(120000)
  expect(wheel).toBeTruthy()
  expect((await (await request.get(`${appUrl}/api/v2/modules`)).json()).modules).toEqual([])
  await page.goto(appUrl)
  await page.getByRole('button', { name: '创建项目', exact: true }).click()
  await page.getByRole('button', { name: '保存项目', exact: true }).click()
  await expect(page.getByLabel('流程保存状态')).toContainText('已保存')
  const projectId = new URL(page.url()).searchParams.get('project')!
  const base = `${appUrl}/api/v2/projects/${projectId}`
  const empty = await (await request.get(`${base}/workspace`)).json()
  expect(empty.draft.workflow.nodes).toEqual([])
  await page.getByRole('button', { name: '模块管理', exact: true }).click()
  await page.getByLabel('选择模块包', { exact: true }).setInputFiles(wheel)
  await expect(page.getByRole('button', { name: '添加节点', exact: true })).toBeVisible()
  await expect.poll(async () => (await (await request.get(`${appUrl}/api/v2/modules`)).json()).modules).toEqual([
    expect.objectContaining({ package_id: 'lifecycle_meter', enabled: true, origin: 'external' }),
  ])
  await page.getByRole('button', { name: '添加节点', exact: true }).click()
  await page.getByRole('dialog', { name: '添加节点', exact: true }).getByRole('button', { name: /External measurement addition/ }).click()
  await expect(page.locator('.react-flow__node')).toHaveCount(1)
  await page.getByRole('button', { name: '调整外部测量', exact: true }).click()
  await page.getByLabel('增加值', { exact: true }).fill('99')
  await page.getByRole('button', { name: '取消测量修改', exact: true }).click()
  await page.getByRole('button', { name: '调整外部测量', exact: true }).click()
  await expect(page.getByLabel('增加值', { exact: true })).toHaveValue('1')
  await page.getByLabel('增加值', { exact: true }).fill('7')
  await page.getByLabel('测量说明', { exact: true }).fill('外部测量 / retained annotation')
  await page.getByRole('button', { name: '采用测量修改', exact: true }).click()
  expect((await (await request.get(`${base}/workspace`)).json()).draft.workflow.nodes).toEqual([])
  await page.getByRole('button', { name: '保存项目', exact: true }).click()
  await expect(page.getByLabel('流程保存状态')).toContainText('已保存')
  const saved = await (await request.get(`${base}/workspace`)).json()
  expect(saved.draft.workflow.nodes[0].node_parameters).toEqual({ amount: 7, note: '外部测量 / retained annotation' })
  await page.reload()
  await page.getByRole('button', { name: '调整外部测量', exact: true }).click()
  await expect(page.getByLabel('增加值', { exact: true })).toHaveValue('7')
  await page.getByRole('button', { name: '取消测量修改', exact: true }).click()
  await page.getByRole('button', { name: '运行流程', exact: true }).click()
  await page.getByRole('button', { name: '准备并查看范围', exact: true }).click()
  const started = page.waitForResponse(response => response.url().endsWith('/runs') && response.request().method() === 'POST')
  await page.getByRole('button', { name: '开始运行已确认范围', exact: true }).click()
  const { run_id } = await (await started).json()
  const runUrl = `${base}/runs/${run_id}`
  await expect.poll(async () => (await (await request.get(runUrl)).json()).status).toBe('succeeded')
  const nodeId = saved.draft.workflow.nodes[0].node_id
  const valueUrl = `${runUrl}/outputs/${nodeId}/reading/values/0`
  const output = await (await request.get(valueUrl)).json()
  expect(output.value).toEqual({ value: 7, note: '外部测量 / retained annotation' })
  await page.getByRole('button', { name: '模块管理', exact: true }).click()
  await page.getByLabel('启用 lifecycle_meter', { exact: true }).uncheck()
  await page.getByRole('button', { name: '应用启用状态', exact: true }).click()
  await expect(page.getByText(/缺失模块：/)).toBeVisible()
  await page.getByRole('button', { name: '保存项目', exact: true }).click()
  await expect(page.getByLabel('流程保存状态')).toContainText('已保存')
  const missing = await (await request.get(`${base}/workspace`)).json()
  expect(missing.draft.workflow).toEqual(saved.draft.workflow)
  expect(missing.ui_state).toEqual(saved.ui_state)
  await page.getByRole('button', { name: '运行流程', exact: true }).click()
  await page.getByRole('button', { name: '准备并查看范围', exact: true }).click()
  await expect(page.getByRole('dialog', { name: '确认运行范围' }).getByRole('alert')).toContainText('Unknown node_type')
  await expect(page.getByRole('button', { name: '开始运行已确认范围', exact: true })).toHaveCount(0)
  await page.getByRole('dialog', { name: '确认运行范围' }).getByRole('button', { name: '关闭', exact: true }).click()
  await page.getByRole('button', { name: '模块管理', exact: true }).click()
  await page.getByRole('button', { name: '卸载 lifecycle_meter', exact: true }).click()
  await expect(page.getByText(/缺失模块：/)).toBeVisible()
  await page.reload()
  expect((await (await request.get(`${appUrl}/api/v2/modules`)).json()).modules).toEqual([])
  expect((await (await request.get(`${base}/workspace`)).json()).draft.workflow).toEqual(saved.draft.workflow)
  expect(await (await request.get(valueUrl)).json()).toEqual(output)
  await page.getByRole('button', { name: '模块管理', exact: true }).click()
  await page.getByLabel('选择模块包', { exact: true }).setInputFiles(wheel)
  await expect(page.getByRole('button', { name: '调整外部测量', exact: true })).toBeVisible()
  await page.getByRole('button', { name: '运行流程', exact: true }).click()
  await page.getByRole('button', { name: '准备并查看范围', exact: true }).click()
  const restarted = page.waitForResponse(response => response.url().endsWith('/runs') && response.request().method() === 'POST')
  await page.getByRole('button', { name: '开始运行已确认范围', exact: true }).click()
  const next = await (await restarted).json()
  await expect.poll(async () => (await (await request.get(`${base}/runs/${next.run_id}`)).json()).status).toBe('succeeded')
  expect((await (await request.get(`${base}/runs/${next.run_id}/outputs/${nodeId}/reading/values/0`)).json()).value).toEqual(output.value)
})
