import { expect, test } from '@playwright/test'

test('empty production carrier creates, manually saves and reopens a project', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Protein Workbench' })).toBeVisible()
  await page.getByRole('button', { name: '创建项目', exact: true }).click()
  await expect(page.locator('.flow-canvas')).toBeVisible()
  await expect(page.locator('.react-flow__node')).toHaveCount(0)
  await page.getByRole('button', { name: '保存项目', exact: true }).click()
  await expect(page.getByLabel('流程保存状态')).toContainText('已保存')
  const name = await page.locator('.project-identity strong').innerText()
  await page.reload()
  await expect(page.locator('.project-identity strong')).toHaveText(name)
  await expect(page.locator('.flow-canvas')).toBeVisible()
  await expect(page.getByLabel('流程保存状态')).toContainText('已保存')
})

test('users install an external wheel, preserve a project across removal and restore execution', async ({ page, request }, testInfo) => {
  await page.goto('/')
  const create = page.getByRole('button', { name: '创建项目', exact: true })
  const projects = page.getByRole('button', { name: '项目', exact: true })
  await expect(create.or(projects)).toBeVisible()
  if (await create.isVisible()) await create.click()
  else {
    await projects.click()
    await page.getByRole('button', { name: '新建项目', exact: true }).click()
  }
  await expect(page.locator('.flow-canvas')).toBeVisible()
  await page.getByRole('button', { name: '模块管理', exact: true }).click()
  await page.getByLabel('选择模块包').setInputFiles(testInfo.config.metadata.externalWheel as string)
  await expect(page.locator('.flow-canvas')).toBeVisible()
  await expect(page.locator('.react-flow__node')).toHaveCount(0)
  await page.locator('.palette-item').filter({ hasText: 'External Echo' }).click()
  await expect(page.locator('.react-flow__node')).toHaveCount(1)
  await page.getByRole('button', { name: '保存项目', exact: true }).click()
  await expect(page.getByLabel('流程保存状态')).toContainText('已保存')
  const projectId = new URL(page.url()).searchParams.get('project')!
  const base = `/api/v2/projects/${projectId}`

  const runFromUi = async () => {
    await page.getByRole('button', { name: '运行流程', exact: true }).click()
    await page.getByRole('button', { name: '准备并查看范围', exact: true }).click()
    const started = page.waitForResponse(response => response.request().method() === 'POST' && response.url().endsWith(`${base}/runs`))
    await page.getByRole('button', { name: '开始运行已确认范围', exact: true }).click()
    const receipt = await (await started).json()
    await expect.poll(async () => (await (await request.get(`${base}/runs/${receipt.run_id}`)).json()).status).toBe('succeeded')
  }
  await runFromUi()
  const saved = await (await request.get(`${base}/workspace`)).json()
  await page.getByRole('button', { name: '模块管理', exact: true }).click()
  await page.getByRole('checkbox', { name: '启用 external_echo', exact: true }).uncheck()
  await page.getByRole('button', { name: '应用启用状态', exact: true }).click()
  await expect(page.locator('.react-flow__node')).toContainText('缺失模块')
  expect(await (await request.get(`${base}/workspace`)).json()).toEqual(saved)
  await page.getByRole('button', { name: '模块管理', exact: true }).click()
  await page.getByRole('checkbox', { name: '启用 external_echo', exact: true }).check()
  await page.getByRole('button', { name: '应用启用状态', exact: true }).click()
  await expect(page.locator('.react-flow__node')).not.toContainText('缺失模块')
  await page.getByRole('button', { name: '模块管理', exact: true }).click()
  await page.getByRole('button', { name: '卸载 external_echo', exact: true }).click()
  await expect(page.locator('.react-flow__node')).toContainText('缺失模块')
  expect(await (await request.get(`${base}/workspace`)).json()).toEqual(saved)
  await page.getByRole('button', { name: '模块管理', exact: true }).click()
  await page.getByLabel('选择模块包').setInputFiles(testInfo.config.metadata.externalWheel as string)
  await expect(page.locator('.react-flow__node')).not.toContainText('缺失模块')
  await runFromUi()
  await page.getByRole('button', { name: '模块管理', exact: true }).click()
  await page.getByRole('button', { name: '安装 protein_io', exact: true }).click()
  await page.getByRole('button', { name: '模块管理', exact: true }).click()
  await expect(page.getByRole('checkbox', { name: '启用 protein_io', exact: true })).toBeChecked()
  await page.getByRole('button', { name: '卸载 protein_io', exact: true }).click()
  await expect(page.locator('.react-flow__node')).toHaveCount(1)
})
