import { expect, test } from '@playwright/test'
import type { ProjectMetadata, RunProjection, Workflow } from '../src/protocol/client'

test('unfinished filter edits preserve the displayed candidates until applied and survive Workflow navigation', async ({ page }, info) => {
  await page.setViewportSize({ width: 1288, height: 989 })
  await page.goto('/')
  await page.getByRole('button', { name: /^Results/ }).click()
  const rows = page.locator('.result-table input[type=checkbox]')
  await expect(rows.first()).toBeVisible()
  const loadAll = page.getByRole('button', { name: '加载全部候选以搜索、筛选和排序' })
  if (await loadAll.isVisible()) await loadAll.click()
  const originalCount = await rows.count()
  await rows.first().check()
  await page.getByText('临时条件筛选 · 支持 AND/OR 分组', { exact: true }).click()
  await page.getByRole('button', { name: '添加条件', exact: true }).click()
  await expect(page.getByRole('button', { name: '应用筛选', exact: true })).toBeDisabled()
  await expect(rows).toHaveCount(originalCount)
  await expect(page.getByText(/条件尚未填写完整/)).toBeVisible()
  await page.getByRole('button', { name: '返回 Workflow', exact: true }).click()
  await page.getByRole('button', { name: /^Results/ }).click()
  await expect(page.getByRole('button', { name: '应用筛选', exact: true })).toBeDisabled()
  await expect(rows).toHaveCount(originalCount)
  await page.getByLabel('临时筛选比较符', { exact: true }).selectOption('>')
  await page.getByLabel('阈值（分数原单位）', { exact: true }).fill(String(Number.MAX_VALUE))
  await expect(rows).toHaveCount(originalCount)
  await page.getByRole('button', { name: '应用筛选', exact: true }).click()
  await expect(rows).toHaveCount(0)
  await expect(page.getByText(/没有匹配当前搜索或条件的候选/)).toBeVisible()
  await page.getByRole('button', { name: '查看已选 (1)', exact: true }).click()
  await expect(page.getByRole('region', { name: '已选候选清单' }).locator('li')).toHaveCount(1)
  await page.screenshot({ path: info.outputPath('results-filter-empty-retained-basket-1288x989.png'), fullPage: true })
  await page.getByRole('button', { name: '清除搜索和条件', exact: true }).click()
  await expect(rows).toHaveCount(originalCount)
  await expect(rows.first()).toBeChecked()
  await page.setViewportSize({ width: 1024, height: 760 })
  await expect(page.getByRole('button', { name: '导出所选 · ZIP' })).toBeVisible()
  await expect(page.getByRole('button', { name: '查看已选 (1)', exact: true })).toBeVisible()
})

test('a prepared selection waits for Results to be active before showing its modal', async ({ page, request }) => {
  const project = await (await request.post('/api/v2/projects', { data: { name: `Selection navigation ${crypto.randomUUID().slice(0, 8)}` } })).json() as ProjectMetadata
  const base = `/api/v2/projects/${project.id}`
  const input = await (await request.post(`${base}/inputs`, { data: { filename: 'navigation.fasta', content_base64: Buffer.from(Array.from({ length: 120 }, (_, index) => `>record ${index + 1}\nACDEFG\n`).join('')).toString('base64') } })).json()
  const workflow: Workflow = { schema_version: '2.1.0', workflow_id: project.id, nodes: [{ node_id: 'batch', node_type_id: 'protein_io.import_sequences', binding_id: 'protein_io.import_sequences.direct', node_parameters: { project_input_ref: input.project_input_ref }, binding_parameters: {} }], edges: [], observation_selectors: [], selection_objectives: [] }
  await request.put(`${base}/workflow/draft`, { data: { workflow } })
  const committed = await (await request.post(`${base}/workflow:commit`, { data: { workflow } })).json()
  const started = await (await request.post(`${base}/runs`, { data: { workflow_commit_id: committed.workflow_commit_id, client_request_id: crypto.randomUUID() } })).json()
  await expect.poll(async () => (await (await request.get(`${base}/runs/${started.run_id}`)).json() as RunProjection).status, { timeout: 30_000 }).toBe('succeeded')
  await page.goto('/')
  await page.getByRole('button', { name: '项目', exact: true }).click()
  const projects = page.getByRole('dialog', { name: '项目与版本' })
  await projects.getByRole('button').filter({ has: page.getByText(project.name, { exact: true }) }).click()
  await projects.getByRole('button', { name: '打开项目', exact: true }).click()
  await page.getByRole('button', { name: /^Results/ }).click()
  await page.locator('.result-table input[type=checkbox]').first().check()

  let release!: () => void
  let requested!: () => void
  const gate = new Promise<void>(resolve => { release = resolve })
  const waiting = new Promise<void>(resolve => { requested = resolve })
  await page.route(`**${base}/runs/${started.run_id}/results:collection`, async route => {
    if (route.request().postDataJSON().offset === 100) { requested(); await gate }
    await route.continue()
  })
  try {
    await page.getByRole('button', { name: '勾选保存为流程', exact: true }).click()
    await waiting
    await page.getByRole('button', { name: '返回 Workflow', exact: true }).click()
    await expect(page.getByRole('button', { name: '运行流程', exact: true })).toBeVisible()
  } finally { release() }
  // This enabled button proves the background preparation has completed.
  await expect(page.getByRole('button', { name: '勾选保存为流程', exact: true, includeHidden: true })).toBeEnabled()
  await expect(page.getByRole('dialog', { name: '保存流程操作预览' })).toHaveCount(0)
  await page.getByRole('button', { name: /^Results/ }).click()
  const preview = page.getByRole('dialog', { name: '保存流程操作预览' })
  await expect(preview).toBeVisible()
  await expect(preview.getByRole('button', { name: '确认保存到流程', exact: true })).toBeEnabled()
  await preview.getByRole('button', { name: '取消', exact: true }).click()
  await expect(page.getByRole('button', { name: '勾选保存为流程', exact: true })).toBeFocused()
  await expect(page.locator('.result-table input[type=checkbox]').first()).toBeChecked()
})

test('default canvas output navigation and first Selection save preserve Results in the copied project', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('.canvas-toolbar')).toBeVisible()
  const output = page.locator('.node-results').first()
  await output.locator('summary').click()
  await output.getByRole('button').first().click()
  const source = page.getByLabel('当前结果来源')
  await expect(source).toBeVisible()
  const location = await source.locator('code').textContent()
  const runReceipt = await page.locator('.result-stages > small').textContent()
  await source.getByRole('button', { name: '在画布中定位' }).click()
  await expect(page.locator('.react-flow__node.selected')).toHaveCount(1)
  await page.getByRole('button', { name: /^Results/ }).click()
  await expect(source.locator('code')).toHaveText(location!)
  const checked = page.locator('.result-table input[type=checkbox]').first()
  await checked.check()
  await page.getByRole('button', { name: '勾选保存为流程', exact: true }).click()
  const preview = page.getByRole('dialog', { name: '保存流程操作预览' })
  await preview.getByRole('button', { name: '确认保存到流程', exact: true }).click()
  const receipt = page.locator('.selection-saved')
  await expect(receipt).toContainText('已保存到流程')
  await expect(checked).toBeChecked()
  await expect(source.locator('code')).toHaveText(location!)
  await expect(page.locator('.result-stages > small')).toHaveText(runReceipt!)
  const newNodeIds = await receipt.locator('li code').allTextContents()
  expect(newNodeIds.length).toBeGreaterThan(0)
  await receipt.getByRole('button', { name: '查看新增节点' }).click()
  for (const id of newNodeIds) await expect(page.getByTestId(`rf__node-${id}`)).toHaveClass(/selected/)
  await expect(page.locator('.immutable-pill')).toHaveCount(0)
})
