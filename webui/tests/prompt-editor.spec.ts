import { test, expect } from '@playwright/test'
const app = process.env.WORKBENCH_TEST_URL ?? 'http://127.0.0.1:5207'

test('module Prompt edits stay local until explicit workspace save and reopen', async ({ page, request }) => {
  const created = await request.post(`${app}/api/v2/projects`, { data: { name: 'Prompt module editing' } })
  const { id } = await created.json()
  const base = `${app}/api/v2/projects/${id}`
  const workflow = { schema_version: '2.1.0', workflow_id: id, edges: [], nodes: [{ node_id: 'prompt', node_type_id: 'prompt_authoring.author', binding_id: 'prompt_authoring.author.direct', binding_parameters: {}, node_parameters: { document: { chains: [{ chain_id: 'A', length: 3 }] } } }] }
  const saved = await request.put(`${base}/workspace`, { data: { workflow, ui_state: {}, expected_draft_revision: 0, expected_workspace_revision: 0 } })
  expect(saved.status()).toBe(200)
  await page.goto(`${app}/?project=${id}`)
  await page.getByRole('button', { name: 'Prompt Studio', exact: true }).click()
  const editor = page.getByRole('dialog', { name: 'Prompt Studio', exact: true })
  await expect(editor.getByLabel('共享残基矩阵')).toBeVisible()
  await editor.locator('[data-cell]').first().click()
  await editor.getByLabel('指定氨基酸').fill('W')
  await editor.getByRole('button', { name: 'Specify', exact: true }).click()
  await expect(editor.locator('[data-cell]').first()).toContainText('W')
  expect((await (await request.get(`${base}/workspace`)).json()).workspace_revision).toBe((await saved.json()).workspace_revision)
  await editor.getByRole('button', { name: '采用 ProteinPrompt', exact: true }).click()
  await expect(editor).not.toBeVisible()
  expect((await (await request.get(`${base}/workspace`)).json()).draft.workflow.nodes[0].node_parameters.document).toEqual(workflow.nodes[0].node_parameters.document)
  await page.getByRole('button', { name: '保存项目', exact: true }).click()
  await expect.poll(async () => (await (await request.get(`${base}/workspace`)).json()).draft.workflow.nodes[0].node_parameters.document.track_edits).toContainEqual(expect.objectContaining({ track: 'sequence', value: 'W' }))
  await page.reload()
  await page.getByRole('button', { name: 'Prompt Studio', exact: true }).click()
  await expect(editor.locator('[data-cell]').first()).toContainText('W')
})

test('partial adoption creates an inserted target by chain and position without an identity input', async ({ page, request }) => {
  const { id } = await (await request.post(`${app}/api/v2/projects`, { data: { name: 'Partial adoption' } })).json()
  const base = `${app}/api/v2/projects/${id}`
  const node = (node_id: string, chain_id: string, sequence: string) => ({ node_id, node_type_id: 'prompt_authoring.author', binding_id: 'prompt_authoring.author.direct', binding_parameters: {}, node_parameters: { document: { chains: [{ chain_id, length: 1 }], track_edits: [{ track: 'sequence', action: 'replace', residue_id: `${chain_id}:1`, value: sequence }] } } })
  const workflow = { schema_version: '2.1.0', workflow_id: id, nodes: [node('source', 'B', 'W'), node('target', 'A', 'C')], edges: [{ source_node_id: 'source', source_port: 'protein_prompt', target_node_id: 'target', target_port: 'merge_sources' }] }
  const saved = await request.put(`${base}/workspace`, { data: { workflow, ui_state: {}, expected_draft_revision: 0, expected_workspace_revision: 0 } })
  expect(saved.status()).toBe(200)
  await page.goto(`${app}/?project=${id}`)
  await page.locator('[data-id="target"]').getByRole('button', { name: 'Prompt Studio', exact: true }).click()
  await page.getByRole('button', { name: '合并来源', exact: true }).click()
  const merge = page.getByRole('dialog', { name: '合并来源', exact: true })
  await merge.getByRole('button', { name: '添加手动对应行' }).click()
  await merge.getByLabel('对应 1 类型').selectOption('target_gap')
  await merge.getByLabel('对应 1 目标', { exact: true }).selectOption('A:1')
  await merge.getByRole('button', { name: '添加手动对应行' }).click()
  await merge.getByLabel('对应 2 类型').selectOption('insert')
  await merge.getByLabel('对应 2 来源').selectOption('B:1')
  await expect(merge.getByPlaceholder('A:new.identity')).toHaveCount(0)
  await merge.getByLabel('对应 2 新增目标链').selectOption('A')
  await merge.getByLabel('采用 B:1 sequence').check()
  await merge.getByLabel('sequence Mask 处理').selectOption('preserve')
  await merge.getByRole('button', { name: '预览区域合并' }).click()
  await merge.getByRole('button', { name: '应用操作', exact: true }).click()
  await merge.getByRole('button', { name: '返回矩阵', exact: true }).click()
  await page.getByRole('button', { name: '采用 ProteinPrompt', exact: true }).click()
  await page.getByRole('button', { name: '保存项目', exact: true }).click()
  await expect.poll(async () => (await (await request.get(`${base}/workspace`)).json()).draft.workflow.nodes[1].node_parameters.document.source_merges?.length).toBe(1)
  await page.reload()
  await page.locator('[data-id="target"]').getByRole('button', { name: 'Prompt Studio', exact: true }).click()
  const matrix = page.getByLabel('共享残基矩阵')
  await expect(matrix.locator('[data-cell]').filter({ hasText: /^C/ })).toHaveCount(1)
  await expect(matrix.locator('[data-cell]').filter({ hasText: /^W/ })).toHaveCount(1)
})

