import { expect, test } from '@playwright/test'

test('modal keyboard journey traps focus, isolates shortcuts and restores each opener', async ({ page }) => {
  await page.goto('/tests/fixtures/interaction-dialog.html')
  const opener = page.getByRole('button', { name: '打开编辑' })
  await opener.click()
  const dialog = page.getByRole('dialog', { name: '编辑', exact: true })
  await expect(dialog.getByLabel('名称')).toBeFocused()
  await dialog.getByLabel('名称').fill('新名称')
  await dialog.getByLabel('名称').dispatchEvent('keydown', { key: 'Escape', code: 'Escape', isComposing: true })
  await expect(dialog).toBeVisible()
  await expect(dialog.getByLabel('名称')).toHaveValue('新名称')
  await page.keyboard.press('Shift+Tab')
  await expect(dialog.getByRole('button', { name: '关闭', exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(dialog.getByLabel('名称')).toBeFocused()
  await dialog.getByRole('button', { name: '更多设置' }).click()
  await expect(page.getByRole('dialog', { name: '更多设置' }).getByLabel('数值')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog.getByRole('button', { name: '更多设置' })).toBeFocused()
  await expect(dialog.getByLabel('名称')).toHaveValue('新名称')
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(opener).toBeFocused()
  await expect(page.getByLabel('背景快捷键次数')).toHaveText('0')
})


test('busy modal retains focus and content until an explicit operation completes', async ({ page }) => {
  await page.goto('/tests/fixtures/interaction-dialog.html')
  await page.getByRole('button', { name: '打开编辑' }).click()
  const dialog = page.getByRole('dialog', { name: '编辑', exact: true })
  await dialog.getByLabel('名称').fill('保留输入')
  await dialog.getByLabel('等待保存').check()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeVisible()
  await expect(dialog.getByLabel('名称')).toHaveValue('保留输入')
  await dialog.getByLabel('等待保存').uncheck()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
})
