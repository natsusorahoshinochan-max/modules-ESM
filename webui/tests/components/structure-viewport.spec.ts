import { expect, test, type Page } from '@playwright/test'
import type { PromptRigidTransform } from '../../src/protocol/client'

test.use({ viewport: { width: 1288, height: 989 } })

async function boxAll(page: Page, cancel = false) {
  const viewport = page.getByLabel('三维结构视口', { exact: true })
  await viewport.focus()
  await page.keyboard.press('b')
  await expect(page.locator('.sv-markers i')).toHaveCount(3)
  const bounds = await page.locator('.sv-canvas').boundingBox()
  await page.mouse.move(bounds!.x + 4, bounds!.y + 65)
  await page.mouse.down()
  await page.mouse.move(bounds!.x + bounds!.width - 4, bounds!.y + bounds!.height - 60, { steps: 5 })
  if (cancel) await page.keyboard.press('Escape')
  await page.mouse.up()
}

test('through box cancellation, selection modes, and numeric axis changes are one operation', async ({ page }) => {
  await page.goto('/tests/support/structure-viewport.html')
  await boxAll(page, true)
  await expect(page.getByLabel('选中残基', { exact: true })).toHaveText('')
  await boxAll(page)
  await expect(page.getByLabel('选中残基', { exact: true })).toHaveText('A1,A2,A3')
  const viewport = page.getByLabel('三维结构视口', { exact: true })
  await viewport.focus()
  await page.keyboard.press('g')
  await page.keyboard.press('x')
  await page.keyboard.press('2')
  await page.keyboard.press('y')
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('已确认变换')).toContainText('"translation":[0,2,0]')
  await page.keyboard.press('r')
  await page.keyboard.press('3')
  await page.keyboard.press('0')
  await page.keyboard.press('z')
  await page.keyboard.press('Escape')
  await expect(page.getByLabel('取消次数')).toHaveText('1')
  expect(JSON.parse(await page.getByLabel('已确认变换').innerText())).toHaveLength(1)
  await page.getByLabel('三维选择方式').selectOption('remove')
  await boxAll(page)
  await expect(page.getByLabel('选中残基', { exact: true })).toHaveText('')
})


test('refreshing a model preserves the camera and cancelled late previews cannot commit', async ({ page }) => {
  await page.goto('/tests/support/structure-viewport.html')
  await boxAll(page)
  const viewport = page.getByLabel('三维结构视口', { exact: true })
  const bounds = (await page.locator('.sv-canvas').boundingBox())!
  await page.mouse.move(bounds.x + 300, bounds.y + 240)
  await page.mouse.down({ button: 'middle' })
  await page.mouse.move(bounds.x + 370, bounds.y + 300, { steps: 8 })
  await page.mouse.up({ button: 'middle' })
  await viewport.focus()
  await page.keyboard.press('b')
  await expect(page.locator('.sv-markers i')).toHaveCount(3)
  const before = await page.locator('.sv-markers i').evaluateAll(markers => markers.map(marker => marker.getAttribute('style')))
  await page.getByRole('button', { name: '刷新模型' }).click()
  await expect(page.getByLabel('模型版本')).toHaveText('1')
  await expect.poll(() => page.locator('.sv-markers i').evaluateAll(markers => markers.map(marker => marker.getAttribute('style')))).toEqual(before)
  await viewport.focus()
  await page.keyboard.press('Escape')
  await page.getByLabel('延迟预览').check()
  await viewport.focus()
  await page.keyboard.press('g')
  await page.keyboard.press('x')
  await page.keyboard.press('2')
  await page.keyboard.press('Enter')
  await expect(page.getByRole('button', { name: '完成预览响应' })).toBeEnabled()
  await page.keyboard.press('Escape')
  await page.getByRole('button', { name: '完成预览响应' }).click()
  await expect(page.getByRole('button', { name: '完成预览响应' })).toBeDisabled()
  await expect(page.getByLabel('已确认变换')).toHaveText('[]')
  await expect(page.getByLabel('取消次数')).toHaveText('1')
  await expect(page.getByLabel('选中残基', { exact: true })).toHaveText('A1,A2,A3')
})

test('free mouse transforms and direction-first numeric distance use the viewport modal', async ({ page }) => {
  await page.goto('/tests/support/structure-viewport.html')
  await boxAll(page)
  const viewport = page.getByLabel('三维结构视口', { exact: true })
  const bounds = (await viewport.locator('.sv-canvas').boundingBox())!
  const center = { x: bounds.x + bounds.width / 2, y: bounds.y + bounds.height / 2 }
  const commits = async (): Promise<PromptRigidTransform[]> => JSON.parse(await page.getByLabel('已确认变换').innerText())
  await page.mouse.move(center.x, center.y)
  await viewport.focus()
  await page.keyboard.press('g')
  await page.mouse.move(center.x + 40, center.y - 30)
  await expect(viewport.locator('.sv-status')).toContainText('视平面')
  await page.keyboard.press('Enter')
  await expect.poll(async () => (await commits()).length).toBe(1)
  const moved = (await commits())[0].translation
  expect(moved[0]).toBeGreaterThan(0)
  expect(moved[1]).toBeGreaterThan(0)
  expect(moved[2]).toBeCloseTo(0)

  await page.mouse.move(center.x + 120, center.y)
  await page.keyboard.press('r')
  await page.mouse.move(center.x, center.y - 110)
  await expect(viewport.locator('.sv-status')).toContainText('视线轴')
  await page.mouse.click(center.x, center.y - 110)
  await expect.poll(async () => (await commits()).length).toBe(2)
  const rotation = (await commits())[1].rotation_matrix
  expect(Math.abs(rotation[0][1])).toBeGreaterThan(0.5)
  expect(rotation[2][2]).toBeCloseTo(1)
  expect(rotation[0][2]).toBeCloseTo(0)
  expect(rotation[1][2]).toBeCloseTo(0)

  await page.mouse.move(center.x, center.y)
  await page.keyboard.press('g')
  await page.keyboard.press('2')
  await expect(viewport.getByRole('button', { name: '确认', exact: true })).toBeDisabled()
  await expect(viewport.locator('.sv-status')).toContainText('移动鼠标建立方向')
  await page.mouse.move(center.x + 45, center.y - 20)
  await page.keyboard.press('x')
  await page.keyboard.press('x')
  await expect(viewport.locator('.sv-status')).toContainText('视平面')
  await page.keyboard.press('Enter')
  await expect.poll(async () => (await commits()).length).toBe(3)
  expect(Math.hypot(...(await commits())[2].translation)).toBeCloseTo(2)
})

test('local box add is unique and remove retains the other selected residue', async ({ page }) => {
  await page.goto('/tests/support/structure-viewport.html')
  const viewport = page.getByLabel('三维结构视口', { exact: true })
  async function boxMarker(index: number, mode: 'replace' | 'add' | 'remove') {
    await page.getByLabel('三维选择方式').selectOption(mode)
    await viewport.focus()
    await page.keyboard.press('b')
    await expect(viewport.locator('.sv-markers i')).toHaveCount(3)
    const marker = (await viewport.locator('.sv-markers i').nth(index).boundingBox())!
    await page.mouse.move(marker.x - 4, marker.y - 4)
    await page.mouse.down()
    await page.mouse.move(marker.x + marker.width + 4, marker.y + marker.height + 4)
    await page.mouse.up()
  }
  await boxMarker(0, 'replace')
  await expect(page.getByLabel('选中残基', { exact: true })).toHaveText('A1')
  await boxMarker(1, 'add')
  await expect(page.getByLabel('选中残基', { exact: true })).toHaveText('A1,A2')
  await boxMarker(1, 'add')
  await expect(page.getByLabel('选中残基', { exact: true })).toHaveText('A1,A2')
  await boxMarker(0, 'remove')
  await expect(page.getByLabel('选中残基', { exact: true })).toHaveText('A2')
})

